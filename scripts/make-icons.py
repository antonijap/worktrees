"""Regenerates Sources/Worktrees/Icons.swift from downloaded SVGs.

Usage: python3 scripts/make-icons.py <dir with lucide/ and octicons/ subfolders>
Lucide SVGs come from cdn.jsdelivr.net/npm/lucide-static@0.469.0/icons/<name>.svg
(brush-cleaning is newer, from lucide-static@0.511.0),
Octicons from cdn.jsdelivr.net/npm/@primer/octicons@19.15.0/build/svg/<name>-16.svg (saved as <name>.svg).
"""
import os, re, sys

base = sys.argv[1]
OCTICONS = ['check', 'kebab-horizontal', 'alert', 'comment', 'dot-fill', 'dash', 'question', 'mark-github', 'x']
# PR-state glyphs, GitHub's own. Prefixed so they don't clash with Lucide's.
PR_OCTICONS = ['git-branch', 'git-pull-request', 'git-pull-request-draft', 'git-pull-request-closed', 'git-merge']
# Heavier strokes where a thin line looks weak next to the solid app icons.
STROKE = {'trash-2': '2.2', 'copy': '2.4'}
lucide = sorted(f[:-4] for f in os.listdir(os.path.join(base, 'lucide')) if f.endswith('.svg'))


def case(name):
    parts = name.replace('-2', '2').split('-')
    return parts[0] + ''.join(p.capitalize() for p in parts[1:])


def clean(svg, name):
    if name in STROKE:
        svg = svg.replace('stroke-width="2"', f'stroke-width="{STROKE[name]}"')
    svg = re.sub(r'<title>.*?</title>', '', svg)
    svg = re.sub(r'<!--.*?-->', '', svg, flags=re.S)
    svg = re.sub(r'\s*\n\s*', ' ', svg).strip().replace('> <', '><')
    return svg.replace('\\', '\\\\').replace('"', '\\"')


entries = [(n, 'lucide') for n in lucide] + [(n, 'octicons') for n in OCTICONS]
entries += [(n, 'octicons') for n in PR_OCTICONS]
CASE_NAMES = {n: 'pr' + case(n)[0].upper() + case(n)[1:] for n in PR_OCTICONS}
out = [
    'import AppKit', 'import SwiftUI', '',
    '// Line icons: Lucide 0.469.0 (brush-cleaning from 0.511.0), ISC licence. https://lucide.dev',
    '// Badge symbols and the GitHub mark: Octicons 19.15.0 by GitHub, MIT licence. https://primer.style/octicons',
    '// Generated by scripts/make-icons.py. Embedded as SVG strings and rendered by NSImage as template images.',
    'enum IconName: String, CaseIterable {',
]
out += [f'    case {CASE_NAMES.get(n, case(n)) if src == "octicons" else case(n)} = "{src}/{n}"' for n, src in entries]
out += ['', '    fileprivate var svg: String {', '        switch self {']
for n, src in entries:
    with open(os.path.join(base, src, n + '.svg')) as f:
        name = CASE_NAMES.get(n, case(n)) if src == 'octicons' else case(n)
        out.append(f'        case .{name}: "{clean(f.read(), n)}"')
out += ['        }', '    }', '', '''    @MainActor private static var cache: [IconName: NSImage] = [:]

    @MainActor var image: NSImage {
        if let cached = Self.cache[self] { return cached }
        let image = NSImage(data: Data(svg.utf8)) ?? NSImage()
        image.isTemplate = true
        Self.cache[self] = image
        return image
    }
}

/// A line icon tinted with the current foreground style.
struct Icon: View {
    let name: IconName
    var size: CGFloat = 16

    var body: some View {
        Image(nsImage: name.image)
            .resizable()
            .renderingMode(.template)
            .interpolation(.high)
            .frame(width: size, height: size)
            .accessibilityHidden(true)
    }
}
''']
with open(os.path.join(os.path.dirname(__file__), '..', 'Sources', 'Worktrees', 'Icons.swift'), 'w') as f:
    f.write('\n'.join(out))
print(f'{len(entries)} icons')
